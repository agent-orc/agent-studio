using System.Text;

namespace AgentRunner.RunTargets;

/// <summary>One public route: the domains of an environment and its current container.</summary>
public sealed record RunTargetRoute(string AppKey, IReadOnlyList<string> Domains, string Edge, string Upstream);

/// <summary>Edge settings that come from the host's own configuration, never from Studio.</summary>
public sealed record RunTargetEdgeSettings(
    string? AcmeEmail,
    bool CloudflareOriginCertificate,
    IReadOnlyList<string> CloudflareTrustedProxies);

public sealed record RunTargetCaddyfileResult(string Text, IReadOnlyList<string> ConflictingAppKeys);

/// <summary>
/// Renders the edge Caddyfile. <c>acme</c> sites get Caddy's automatic HTTPS.
/// <c>cloudflare</c> sites sit behind the Cloudflare proxy: they use the
/// operator's origin certificate when one is installed (SSL mode Full strict),
/// otherwise Caddy's internal CA (SSL mode Full), so no ACME challenge has to
/// pass through the proxy. A domain belongs to the first app that declares it;
/// a later app with the same domain is reported as a conflict and not routed.
/// </summary>
public static class RunTargetCaddyfile
{
    public const string OriginCertificate = "/certs/origin.pem";
    public const string OriginKey = "/certs/origin.key";

    public static RunTargetCaddyfileResult Render(IEnumerable<RunTargetRoute> routes, RunTargetEdgeSettings settings)
    {
        var text = new StringBuilder();
        text.Append("# Generated by agent-host run-target (IP-1). Changes are overwritten.\n");
        text.Append("{\n\tadmin localhost:2019\n");
        if (settings.AcmeEmail is { Length: > 0 } email) text.Append("\temail ").Append(email).Append('\n');
        if (settings.CloudflareTrustedProxies.Count > 0)
        {
            text.Append("\tservers {\n\t\ttrusted_proxies static ")
                .Append(string.Join(' ', settings.CloudflareTrustedProxies))
                .Append("\n\t\tclient_ip_headers CF-Connecting-IP\n\t}\n");
        }
        text.Append("}\n");
        var claimed = new HashSet<string>(StringComparer.Ordinal);
        var conflicts = new List<string>();
        foreach (var route in routes.OrderBy(item => item.AppKey, StringComparer.Ordinal))
        {
            var domains = route.Domains.Where(RunTargetNames.IsDomain).Distinct(StringComparer.Ordinal).ToArray();
            if (domains.Length == 0) continue;
            if (domains.Any(claimed.Contains))
            {
                conflicts.Add(route.AppKey);
                continue;
            }
            claimed.UnionWith(domains);
            text.Append('\n').Append(string.Join(", ", domains)).Append(" {\n");
            if (route.Edge == "cloudflare")
            {
                text.Append(settings.CloudflareOriginCertificate
                    ? $"\ttls {OriginCertificate} {OriginKey}\n"
                    : "\ttls internal\n");
            }
            text.Append("\tencode zstd gzip\n\treverse_proxy ").Append(route.Upstream).Append("\n}\n");
        }
        return new(text.ToString(), conflicts);
    }
}
