using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;

namespace AgentRunner.RunTargets;

/// <summary>
/// Renders Docker Compose files for one app revision and for the edge. An app
/// file publishes no port, never uses the host network, and mounts nothing from
/// the host except its secret files. Each secret reference is a compose file
/// secret read from <see cref="RunTargetSecretFiles"/> on tmpfs and mounted at
/// <c>/run/secrets/&lt;ref&gt;</c>; the container gets only the path, in
/// <c>NAME_FILE</c>, so Docker's container configuration holds no value.
/// Every free-text value has <c>$</c> doubled so Compose does not interpolate
/// variables from the agent's environment.
/// </summary>
public static class RunTargetComposeFile
{
    private static readonly JsonSerializerOptions Quote = new() { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    public static string App(RunTargetEnvironmentSpec spec, string appKey, string revision, string secretDirectory)
    {
        var project = appKey + "-" + revision;
        var text = new StringBuilder();
        text.Append("# Generated by agent-host run-target (IP-1). Secret values are never written here.\n");
        text.Append("name: ").Append(Q(project)).Append('\n');
        text.Append("services:\n  app:\n");
        text.Append("    image: ").Append(Literal(spec.Artifact!)).Append('\n');
        text.Append("    container_name: ").Append(Q(project)).Append('\n');
        // Docker restarts a crash a few times; the host agent then takes over
        // with its own backoff and reports a crash loop (RunTargetCrashPolicy).
        text.Append("    restart: \"on-failure:3\"\n");
        text.Append("    cpus: ").Append(spec.Resources.Cpus.ToString("0.0#", CultureInfo.InvariantCulture)).Append('\n');
        text.Append("    mem_limit: \"").Append(spec.Resources.MemoryMb).Append("m\"\n");
        text.Append("    memswap_limit: \"").Append(spec.Resources.MemoryMb).Append("m\"\n");
        text.Append("    pids_limit: ").Append(spec.Resources.PidsLimit).Append('\n');
        text.Append("    security_opt:\n      - \"no-new-privileges:true\"\n");
        var variables = spec.Variables.OrderBy(item => item.Key, StringComparer.Ordinal).ToArray();
        var secretRefs = spec.SecretRefs.Order(StringComparer.Ordinal).ToArray();
        if (variables.Length + secretRefs.Length > 0)
        {
            text.Append("    environment:\n");
            foreach (var (name, value) in variables)
                text.Append("      - ").Append(Literal(name + "=" + value)).Append('\n');
            foreach (var secretRef in secretRefs)
            {
                text.Append("      - ").Append(Literal(RunTargetNames.SecretFileVariable(secretRef) + "=/run/secrets/" + secretRef))
                    .Append('\n');
            }
        }
        if (secretRefs.Length > 0)
        {
            text.Append("    secrets:\n");
            foreach (var secretRef in secretRefs) text.Append("      - ").Append(Literal(secretRef)).Append('\n');
        }
        text.Append("    labels:\n");
        text.Append("      agent-studio.run-target: \"app\"\n");
        text.Append("      agent-studio.project: ").Append(Literal(spec.Project)).Append('\n');
        text.Append("      agent-studio.environment: ").Append(Literal(spec.EnvironmentId)).Append('\n');
        text.Append("      agent-studio.revision: ").Append(Literal(revision)).Append('\n');
        text.Append("    logging:\n      driver: \"json-file\"\n      options:\n        max-size: \"10m\"\n        max-file: \"3\"\n");
        text.Append("    networks:\n      app:\n        aliases:\n          - ").Append(Q(project)).Append('\n');
        text.Append("networks:\n  app:\n    name: ").Append(Q(RunTargetNames.AppNetwork(appKey))).Append("\n    external: true\n");
        if (secretRefs.Length > 0)
        {
            text.Append("secrets:\n");
            foreach (var secretRef in secretRefs)
            {
                text.Append("  ").Append(Q(secretRef)).Append(":\n    file: ")
                    .Append(Literal(Path.Combine(secretDirectory, secretRef))).Append('\n');
            }
        }
        return text.ToString();
    }

    /// <summary>
    /// The edge is the only container with published ports. App networks are
    /// attached at run time with <c>docker network connect</c>, so adding an app
    /// never recreates the edge.
    /// </summary>
    public static string Edge(string image, string caddyConfigDirectory, string? certificateDirectory,
        int httpPort, int httpsPort)
    {
        var text = new StringBuilder();
        text.Append("# Generated by agent-host run-target (IP-1).\n");
        text.Append("name: ").Append(Q(RunTargetNames.EdgeContainer)).Append('\n');
        text.Append("services:\n  edge:\n");
        text.Append("    image: ").Append(Literal(image)).Append('\n');
        text.Append("    container_name: ").Append(Q(RunTargetNames.EdgeContainer)).Append('\n');
        text.Append("    restart: \"unless-stopped\"\n");
        text.Append("    cpus: 1.0\n    mem_limit: \"256m\"\n    pids_limit: 256\n");
        text.Append("    security_opt:\n      - \"no-new-privileges:true\"\n");
        text.Append("    ports:\n");
        text.Append("      - ").Append(Q($"{httpPort}:80")).Append('\n');
        text.Append("      - ").Append(Q($"{httpsPort}:443")).Append('\n');
        text.Append("      - ").Append(Q($"{httpsPort}:443/udp")).Append('\n');
        text.Append("    volumes:\n");
        text.Append("      - \"rt-edge-data:/data\"\n      - \"rt-edge-config:/config\"\n");
        // A directory mount: an atomic rename of the Caddyfile is visible to
        // the container, a single-file bind mount would keep the old inode.
        text.Append("      - ").Append(Literal(caddyConfigDirectory + ":/etc/caddy:ro")).Append('\n');
        if (certificateDirectory is not null)
            text.Append("      - ").Append(Literal(certificateDirectory + ":/certs:ro")).Append('\n');
        text.Append("    labels:\n      agent-studio.run-target: \"edge\"\n");
        text.Append("    networks:\n      - edge\n");
        text.Append("volumes:\n  rt-edge-data:\n    name: \"rt-edge-data\"\n  rt-edge-config:\n    name: \"rt-edge-config\"\n");
        text.Append("networks:\n  edge:\n    name: ").Append(Q(RunTargetNames.EdgeNetwork)).Append('\n');
        return text.ToString();
    }

    /// <summary>A JSON string is a valid YAML double-quoted scalar.</summary>
    private static string Q(string value) => JsonSerializer.Serialize(value, Quote);

    /// <summary>A quoted scalar that Compose takes literally: <c>$$</c> is its escape for <c>$</c>.</summary>
    private static string Literal(string value) => Q(value.Replace("$", "$$", StringComparison.Ordinal));
}
