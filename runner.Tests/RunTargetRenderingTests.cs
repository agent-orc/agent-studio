    [Fact]
    public async Task FileSecretSource_ResolvesOnlyInsideTheProjectsOwnRoot()
    {
        using var workspace = new AgentStudio.TestSupport.TempWorkspace("run-target-secret-roots");
        var root = workspace.Directory("secrets");
        Directory.CreateDirectory(Path.Combine(root, "demo shop"));
        Directory.CreateDirectory(Path.Combine(root, "demo%20shop"));
        Directory.CreateDirectory(Path.Combine(root, "other"));
        await File.WriteAllTextAsync(Path.Combine(root, "demo%20shop", "database-url"), "demo-value\n");
        await File.WriteAllTextAsync(Path.Combine(root, "other", "stripe-key"), "other-value");
        await File.WriteAllTextAsync(Path.Combine(root, "stripe-key"), "host-wide-value");
        var source = new FileRunTargetSecretSource(root);

        Assert.Equal("demo-value", await source.ReadAsync("Demo Shop", "database-url", CancellationToken.None));
        Assert.Null(await source.ReadAsync("Demo Shop", "stripe-key", CancellationToken.None));
        Assert.Null(await source.ReadAsync("Demo Shop", "../other/stripe-key", CancellationToken.None));
        Assert.Null(await source.ReadAsync("..", "stripe-key", CancellationToken.None));
        Assert.Equal("other-value", await source.ReadAsync("other", "stripe-key", CancellationToken.None));
    }

    [Fact]
    public void Options_PinTheEdgeImageByDefault_AndRefuseAMovingTag()
    {
        var runner = new RunnerOptions
        {
            ServerUrl = "http://studio", RunnerId = "run-host", RunnerName = "run-host", Hostname = "run-host",
            BackendName = "test", WorkDir = "/tmp/run-host", BaseBranch = "main", StateDir = "/var/lib/agent-host",
        };

        var options = RunTargetOptions.From(runner, _ => null);

        Assert.True(RunTargetNames.IsDigest(options.Reconciler.EdgeImage));
        Assert.Equal("/run/agent-host/run-target-secrets", options.SecretRuntimeDirectory);
        Assert.Throws<ArgumentException>(() => RunTargetOptions.From(runner,
            name => name == "RUN_TARGET_EDGE_IMAGE" ? "caddy:2-alpine" : null));
        Assert.Throws<ArgumentException>(() => RunTargetOptions.From(runner,
            name => name == "RUN_TARGET_SECRET_RUNTIME_DIR" ? "relative/secrets" : null));
    }
