    [Fact]
    public void AppCompose_EscapesDollarInEveryFreeTextValue_SoComposeInterpolatesNothing()
    {
        var spec = Spec() with { Project = "shop-$HOME", EnvironmentId = "prod${USER}" };

        var text = RunTargetComposeFile.App(spec, "rt-key", "abc123", "/run/$secrets");

        Assert.Contains("      agent-studio.project: \"shop-$$HOME\"\n", text);
        Assert.Contains("      agent-studio.environment: \"prod$${USER}\"\n", text);
        Assert.Contains("    file: \"/run/$$secrets/database-url\"\n", text);
        Assert.DoesNotMatch(@"(?<!\$)\$(?!\$)[A-Za-z{]", text.Replace("$$", "", StringComparison.Ordinal));
    }

