using AgentRunner.RunTargets;
using Xunit;

namespace AgentRunner.Tests;

/// <summary>IP-1 Caddyfile and compose generation, host-side validation, and the crash backoff matrix.</summary>
public sealed class RunTargetRenderingTests
{
    private static readonly string Artifact = "registry.example/app@sha256:" + new string('a', 64);
    private static readonly RunTargetEdgeSettings Acme = new("ops@example.com", false, []);

    private static RunTargetEnvironmentSpec Spec(string environment = "stage") => new(
        "Demo Shop", environment, "stage", Artifact, 3000, "/healthz", ["shop.example.com"], "acme",
        new Dictionary<string, string> { ["LOG_LEVEL"] = "info", ["GREETING"] = "costs $5 \"now\"" },
        ["database-url", "stripe.key"], new RunTargetResources(1.5, 768, 200), null, null, false);

    [Fact]
    public void Caddyfile_AcmeSite_GetsAutomaticHttps_AndRoutesToTheCurrentContainer()
    {
        var result = RunTargetCaddyfile.Render(
            [new RunTargetRoute("rt-b", ["www.shop.example.com", "shop.example.com"], "acme", "rt-b-123:3000")], Acme);

        Assert.Equal("""
            # Generated by agent-host run-target (IP-1). Changes are overwritten.
            {
            	admin localhost:2019
            	email ops@example.com
            }

            www.shop.example.com, shop.example.com {
            	encode zstd gzip
            	reverse_proxy rt-b-123:3000
            }

            """.Replace("\r\n", "\n", StringComparison.Ordinal), result.Text);
        Assert.Empty(result.ConflictingAppKeys);
    }

    [Theory]
    [InlineData(false, "\ttls internal\n")]
    [InlineData(true, "\ttls /certs/origin.pem /certs/origin.key\n")]
    public void Caddyfile_CloudflareSite_AvoidsAcme_AndUsesTheOriginCertificateWhenInstalled(bool originCertificate, string tls)
    {
        var settings = new RunTargetEdgeSettings(null, originCertificate, ["173.245.48.0/20", "2400:cb00::/32"]);

        var text = RunTargetCaddyfile.Render(
            [new RunTargetRoute("rt-a", ["proxied.example.com"], "cloudflare", "rt-a-1:8080")], settings).Text;

        Assert.Contains("proxied.example.com {\n" + tls, text);
        Assert.Contains("trusted_proxies static 173.245.48.0/20 2400:cb00::/32", text);
        Assert.Contains("client_ip_headers CF-Connecting-IP", text);
        Assert.DoesNotContain("email", text);
    }

    [Fact]
    public void Caddyfile_RoutesEachDomainOnce_AndReportsTheConflictingApp()
    {
        var result = RunTargetCaddyfile.Render(
        [
            new RunTargetRoute("rt-z", ["app.example.com"], "acme", "rt-z-1:80"),
            new RunTargetRoute("rt-a", ["app.example.com", "other.example.com"], "acme", "rt-a-1:80"),
            new RunTargetRoute("rt-m", ["bad domain}", "{evil"], "acme", "rt-m-1:80"),
        ], Acme);

        Assert.Equal(["rt-z"], result.ConflictingAppKeys);
        Assert.Contains("app.example.com, other.example.com {\n\tencode zstd gzip\n\treverse_proxy rt-a-1:80", result.Text);
        Assert.DoesNotContain("rt-z-1", result.Text);
        Assert.DoesNotContain("evil", result.Text);
    }

    [Fact]
    public void AppCompose_PublishesNoPort_UsesItsOwnNetwork_LimitsResources_AndNamesSecretsWithoutValues()
    {
        var spec = Spec();
        var key = RunTargetNames.AppKey(spec.Project, spec.EnvironmentId);

        var text = RunTargetComposeFile.App(spec, key, "abc123");

        Assert.DoesNotContain("ports:", text);
        Assert.DoesNotContain("network_mode", text);
        Assert.DoesNotContain("volumes:", text);
        Assert.DoesNotContain("privileged", text);
        Assert.Contains("    restart: \"on-failure:3\"\n", text);
        Assert.Contains("    cpus: 1.5\n    mem_limit: \"768m\"\n    memswap_limit: \"768m\"\n    pids_limit: 200\n", text);
        Assert.Contains("      - \"no-new-privileges:true\"\n", text);
        Assert.Contains("      - \"GREETING=costs $$5 \\\"now\\\"\"\n", text);
        Assert.Contains("      - \"DATABASE_URL\"\n      - \"STRIPE_KEY\"\n", text);
        Assert.Contains($"  app:\n    name: \"{key}-net\"\n    external: true\n", text);
        Assert.Contains($"    image: \"{Artifact}\"\n", text);
    }

    [Fact]
    public void EdgeCompose_IsTheOnlyPublisher_AndMountsTheCaddyDirectoryReadOnly()
    {
        var text = RunTargetComposeFile.Edge("caddy:2-alpine", "/var/lib/agent-host/run-target/edge/caddy", "/etc/agent-host/origin", 8080, 8443);

        Assert.Contains("      - \"8080:80\"\n      - \"8443:443\"\n      - \"8443:443/udp\"\n", text);
        Assert.Contains("\"/var/lib/agent-host/run-target/edge/caddy:/etc/caddy:ro\"", text);
        Assert.Contains("\"/etc/agent-host/origin:/certs:ro\"", text);
        Assert.Contains("    restart: \"unless-stopped\"\n", text);
    }

    [Fact]
    public void Revision_ChangesWithTheContainer_NotWithRouting()
    {
        var spec = Spec();

        Assert.Equal(RunTargetNames.Revision(spec), RunTargetNames.Revision(spec with
        { Domains = ["other.example.com"], Edge = "cloudflare", JobId = "j", LeaseToken = "l", IsRollback = true }));
        Assert.NotEqual(RunTargetNames.Revision(spec), RunTargetNames.Revision(spec with
        { Variables = new Dictionary<string, string> { ["LOG_LEVEL"] = "warn" } }));
        Assert.NotEqual(RunTargetNames.Revision(spec), RunTargetNames.Revision(spec with
        { Resources = new RunTargetResources(2, 768, 200) }));
    }

    [Fact]
    public void AppKey_IsStableDockerSafeAndDistinctPerEnvironment()
    {
        var key = RunTargetNames.AppKey("Demo Shop / Ä", "prod.eu");

        Assert.Matches("^rt-[a-z0-9-]+-[0-9a-f]{8}$", key);
        Assert.Equal(key, RunTargetNames.AppKey("Demo Shop / Ä", "prod.eu"));
        Assert.NotEqual(key, RunTargetNames.AppKey("Demo Shop / Ä", "prod-eu"));
    }

    [Theory]
    [InlineData("artifact", "app:latest")]
    [InlineData("health", "/../admin")]
    [InlineData("domain", "-bad.example.com")]
    [InlineData("edge", "plain")]
    [InlineData("secret", "PATH")]
    [InlineData("secret", "docker-host")]
    [InlineData("variable", "lower")]
    [InlineData("shadow", "LOG_LEVEL")]
    public void Invalid_RefusesWhatTheHostMustNotRun(string field, string value)
    {
        var spec = Spec();
        spec = field switch
        {
            "artifact" => spec with { Artifact = value },
            "health" => spec with { HealthPath = value },
            "domain" => spec with { Domains = [value] },
            "edge" => spec with { Edge = value },
            "secret" => spec with { SecretRefs = [value] },
            "variable" => spec with { Variables = new Dictionary<string, string> { [value] = "x" } },
            _ => spec with { SecretRefs = ["log-level"] },
        };

        Assert.NotNull(RunTargetNames.Invalid(spec));
        Assert.Null(RunTargetNames.Invalid(Spec()));
    }

    [Theory]
    [InlineData(0, 0)]
    [InlineData(1, 10)]
    [InlineData(2, 20)]
    [InlineData(5, 160)]
    [InlineData(6, 300)]
    [InlineData(40, 300)]
    public void CrashBackoff_DoublesFromTenSeconds_UpToFiveMinutes(int attempts, int seconds)
        => Assert.Equal(TimeSpan.FromSeconds(seconds), RunTargetCrashPolicy.Backoff(attempts));

    [Theory]
    [InlineData(4, false)]
    [InlineData(5, true)]
    public void CrashLoop_StartsAtTheFifthRestart(int attempts, bool loop)
        => Assert.Equal(loop, RunTargetCrashPolicy.IsCrashLoop(attempts));
}
