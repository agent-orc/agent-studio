    [Fact]
    public void Caddyfile_AcmeSite_GetsAutomaticHttps_AndRoutesToTheCurrentContainer()
    {
        RunTargetRoute[] routes = [new RunTargetRoute("rt-b", ["www.shop.example.com", "shop.example.com"], "acme", "rt-b-123:3000")];
        var result = RunTargetCaddyfile.Render(routes, RunTargetCaddyfile.ClaimDomains(new Dictionary<string, string>(), routes), Acme);

        var expected = string.Join('\n', [
            "# Generated by agent-host run-target (IP-1). Changes are overwritten.",
            "{", "\tadmin localhost:2019", "\temail ops@example.com", "}", "",
            "www.shop.example.com, shop.example.com {", "\tencode zstd gzip",
            "\treverse_proxy rt-b-123:3000", "}", "",
        ]);
        Assert.Equal(expected, result.Text);
        Assert.Empty(result.ConflictingAppKeys);
    }

    [Theory]
    [InlineData(false, "\ttls internal\n")]
    [InlineData(true, "\ttls /certs/origin.pem /certs/origin.key\n")]
    public void Caddyfile_CloudflareSite_AvoidsAcme_AndUsesTheOriginCertificateWhenInstalled(bool originCertificate, string tls)
    {
        var settings = new RunTargetEdgeSettings(null, originCertificate, ["173.245.48.0/20", "2400:cb00::/32"]);

        var text = RunTargetCaddyfile.Render(
            [new RunTargetRoute("rt-a", ["proxied.example.com"], "cloudflare", "rt-a-1:8080")],
            new Dictionary<string, string> { ["proxied.example.com"] = "rt-a" }, settings).Text;

        Assert.Contains("proxied.example.com {\n" + tls, text);
        Assert.Contains("trusted_proxies static 173.245.48.0/20 2400:cb00::/32", text);
        Assert.Contains("client_ip_headers CF-Connecting-IP", text);
        Assert.DoesNotContain("email", text);
    }

    [Fact]
    public void Caddyfile_KeepsTheFirstClaim_EvenWhenALaterAppSortsFirst()
    {
        RunTargetRoute[] routes =
        [
            new RunTargetRoute("rt-z", ["app.example.com"], "acme", "rt-z-1:80"),
            new RunTargetRoute("rt-a", ["app.example.com", "other.example.com"], "acme", "rt-a-1:80"),
            new RunTargetRoute("rt-m", ["bad domain}", "{evil"], "acme", "rt-m-1:80"),
        ];

        var owners = RunTargetCaddyfile.ClaimDomains(new Dictionary<string, string> { ["app.example.com"] = "rt-z" }, routes);
        var result = RunTargetCaddyfile.Render(routes, owners, Acme);

        Assert.Equal(new Dictionary<string, string> { ["app.example.com"] = "rt-z", ["other.example.com"] = "rt-a" }, owners);
        Assert.Equal(["rt-a"], result.ConflictingAppKeys);
        Assert.Contains("app.example.com {\n\tencode zstd gzip\n\treverse_proxy rt-z-1:80", result.Text);
        Assert.Contains("other.example.com {\n\tencode zstd gzip\n\treverse_proxy rt-a-1:80", result.Text);
        Assert.DoesNotContain("evil", result.Text);
    }

    [Theory]
    [InlineData("rt-gone", "rt-a")]
    [InlineData("rt-z", "rt-z")]
    public void ClaimDomains_ReleasesADomainOnlyWhenItsOwnerIsGoneOrStopsDeclaringIt(string owner, string expected)
    {
        RunTargetRoute[] routes =
        [
            new RunTargetRoute("rt-a", ["app.example.com"], "acme", "rt-a-1:80"),
            new RunTargetRoute("rt-z", ["app.example.com"], "acme", "rt-z-1:80"),
        ];

        var owners = RunTargetCaddyfile.ClaimDomains(new Dictionary<string, string> { ["app.example.com"] = owner }, routes);

        Assert.Equal(expected, owners["app.example.com"]);
        Assert.Equal("rt-a", RunTargetCaddyfile.ClaimDomains(
            new Dictionary<string, string> { ["app.example.com"] = "rt-z" },
            [routes[0], routes[1] with { Domains = ["z.example.com"] }])["app.example.com"]);
    }

