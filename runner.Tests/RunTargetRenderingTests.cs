    [InlineData("/var/lib/agent-host/secrets", false)]
    [InlineData("/mnt/ram disk/s", true)]
    [InlineData("/runner/secrets", false)]
    public void SecretFiles_GoOnlyToAMemoryBackedMount(string path, bool memoryBacked)
    {
        const string mounts = """
            /dev/sda1 / ext4 rw,relatime 0 0
            tmpfs /run tmpfs rw,nosuid,nodev,mode=755 0 0
            /dev/sdb1 /var/lib ext4 rw 0 0
            tmpfs /mnt/ram\040disk tmpfs rw 0 0
            """;

        Assert.Equal(memoryBacked, RunTargetSecretFiles.IsMemoryBacked(path, mounts));
    }

