    [Fact]
    public void Revision_ChangesWithTheContainer_NotWithRouting()
    {
        var spec = Spec();

        Assert.Equal(RunTargetNames.Revision(spec), RunTargetNames.Revision(spec with
        { Domains = ["other.example.com"], Edge = "cloudflare", JobId = "j", LeaseToken = "l", IsRollback = true }));
        Assert.NotEqual(RunTargetNames.Revision(spec), RunTargetNames.Revision(spec with
        { Variables = new Dictionary<string, string> { ["LOG_LEVEL"] = "warn" } }));
        Assert.NotEqual(RunTargetNames.Revision(spec), RunTargetNames.Revision(spec with
        { Resources = new RunTargetResources(2, 768, 200) }));
    }

    [Fact]
    public void AppKey_IsStableDockerSafeAndDistinctPerEnvironment()
    {
        var key = RunTargetNames.AppKey("Demo Shop / Ä", "prod.eu");

        Assert.Matches("^rt-[a-z0-9-]+-[0-9a-f]{20}$", key);
        Assert.Equal(key, RunTargetNames.AppKey("Demo Shop / Ä", "prod.eu"));
        Assert.NotEqual(key, RunTargetNames.AppKey("Demo Shop / Ä", "prod-eu"));
        // Ids that share a slug differ only in the 80-bit hash.
        Assert.Equal(3, new[] { "prod", "prod.", "prod._-" }.Select(id => RunTargetNames.AppKey("demo", id)).Distinct().Count());
        var longest = RunTargetNames.AppKey(new string('p', 64), new string('e', 64)) + "-" + new string('r', 12);
        Assert.True(longest.Length <= 63, longest);
    }

    [Theory]
    [InlineData("artifact", "app:latest")]
    [InlineData("health", "/../admin")]
    [InlineData("domain", "-bad.example.com")]
    [InlineData("edge", "plain")]
    [InlineData("secret", "../db")]
    [InlineData("repeated", "a-b")]
    [InlineData("variable", "lower")]
    [InlineData("shadow", "LOG_LEVEL")]
    [InlineData("shadow-file", "DATABASE_URL_FILE")]
    [InlineData("project", "..")]
    public void Invalid_RefusesWhatTheHostMustNotRun(string field, string value)
    {
        var spec = Spec();
        spec = field switch
        {
            "artifact" => spec with { Artifact = value },
            "health" => spec with { HealthPath = value },
            "domain" => spec with { Domains = [value] },
            "edge" => spec with { Edge = value },
            "secret" => spec with { SecretRefs = [value] },
            "variable" => spec with { Variables = new Dictionary<string, string> { [value] = "x" } },
            "repeated" => spec with { SecretRefs = [value, "a.b"] },
            "shadow-file" => spec with { Variables = new Dictionary<string, string> { [value] = "/tmp/db" } },
            "project" => spec with { Project = value },
            _ => spec with { SecretRefs = ["log-level"] },
        };

        Assert.NotNull(RunTargetNames.Invalid(spec));
        Assert.Null(RunTargetNames.Invalid(Spec()));
    }

