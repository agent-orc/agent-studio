#!/usr/bin/env bash
# Refreshes cloudflare-ips.caddy from Cloudflare's published proxy ranges.
# The Cloudflare edge mode trusts CF-Connecting-IP only from these ranges and
# refuses every other peer, so a stale file locks out new Cloudflare ranges.
#
# Usage: update-cloudflare-ips.sh [--check]
#   --check  Write nothing; exit 1 when the published ranges differ.
# CLOUDFLARE_IPS_BASE_URL replaces https://www.cloudflare.com (tests, mirrors);
# without it, curl may use and follow only HTTPS.
# A range wider than IPv4 /12 or IPv6 /24 is refused: Cloudflare publishes
# none, and a wide range would let arbitrary peers set CF-Connecting-IP.
# After an update, run `docker compose restart edge`.
set -euo pipefail

cd "$(dirname "$0")"
target=cloudflare-ips.caddy
public_caddyfile=Caddyfile.public
base="${CLOUDFLARE_IPS_BASE_URL:-https://www.cloudflare.com}"
check=false
https_only=()
if [ -z "${CLOUDFLARE_IPS_BASE_URL:-}" ]; then
  https_only=(--proto '=https' --proto-redir '=https')
fi
case "${1:-}" in
  --check) check=true ;;
  '') ;;
  *) echo 'Usage: update-cloudflare-ips.sh [--check]' >&2; exit 2 ;;
esac

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# Reads one published list, one CIDR per line, and rejects anything else so a
# changed or truncated response never becomes the edge's trust list.
read_list() {
  local name="$1" pattern="$2" shortest="$3" longest="$4" count=0 line prefix
  curl ${https_only[@]+"${https_only[@]}"} --fail --silent --show-error --location --max-time 30 \
    "$base/$name" > "$work/$name"
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    [ -z "$line" ] && continue
    if ! [[ "$line" =~ $pattern ]]; then
      echo "Unexpected entry in $base/$name: $line" >&2
      exit 1
    fi
    prefix=$((10#${line##*/}))
    if [ "$prefix" -lt "$shortest" ] || [ "$prefix" -gt "$longest" ]; then
      echo "Refusing $line from $base/$name: prefix must be /$shortest to /$longest" >&2
      exit 1
    fi
    printf '%s\n' "$line" >> "$work/ranges"
    count=$((count + 1))
  done < "$work/$name"
  if [ "$count" -eq 0 ]; then
    echo "$base/$name lists no ranges" >&2
    exit 1
  fi
}

: > "$work/ranges"
read_list ips-v4 '^((25[0-5]|2[0-4][0-9]|1?[0-9]?[0-9])\.){3}(25[0-5]|2[0-4][0-9]|1?[0-9]?[0-9])/[0-9]{1,2}$' 12 32
read_list ips-v6 '^[0-9A-Fa-f:]+/[0-9]{1,3}$' 24 128

current_ranges() {
  [ -f "$target" ] || return 0
  sed -n 's/^[[:space:]]*\([0-9A-Fa-f.:]*\/[0-9]*\).*/\1/p' "$target"
}

current_public_ranges() {
  [ -f "$public_caddyfile" ] || return 0
  sed -n 's/^[[:space:]]*@cloudflare remote_ip //p' "$public_caddyfile" \
    | tr ' ' '\n' | sed '/^$/d'
}

if [ "$(grep -c '^[[:space:]]*@cloudflare remote_ip ' "$public_caddyfile")" -ne 1 ]; then
  echo "$public_caddyfile needs exactly one @cloudflare remote_ip matcher" >&2
  exit 1
fi

if [ "$(current_ranges)" = "$(cat "$work/ranges")" ] \
  && [ "$(current_public_ranges)" = "$(cat "$work/ranges")" ]; then
  echo "$target and $public_caddyfile already match Cloudflare's published ranges."
  exit 0
fi

if [ "$check" = true ]; then
  echo "$target or $public_caddyfile differs from Cloudflare's published ranges:" >&2
  diff <(current_ranges) "$work/ranges" >&2 || true
  diff <(current_public_ranges) "$work/ranges" >&2 || true
  exit 1
fi

{
  echo "# Cloudflare's published proxy ranges for the Cloudflare edge mode."
  echo "# Generated by update-cloudflare-ips.sh from $base/ips-v4"
  echo "# and $base/ips-v6. Do not edit by hand."
  echo "# Retrieved: $(date -u +%Y-%m-%d)"
  echo 'trusted_proxies static \'
  sed -e 's/^/	/' -e '$!s/$/ \\/' "$work/ranges"
} > "$work/$target"
matcher="    @cloudflare remote_ip $(paste -sd' ' "$work/ranges")"
awk -v replacement="$matcher" '
  /^[[:space:]]*@cloudflare remote_ip / { print replacement; next }
  { print }
' "$public_caddyfile" > "$work/$public_caddyfile"
diff <(current_ranges) "$work/ranges" || true
mv "$work/$target" "$target"
mv "$work/$public_caddyfile" "$public_caddyfile"
echo "Updated $target and $public_caddyfile. Run 'docker compose restart edge' to apply them."
