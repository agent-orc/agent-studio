#!/usr/bin/env bash
# Refreshes cloudflare-ips.caddy from Cloudflare's published proxy ranges.
# The Cloudflare edge mode trusts CF-Connecting-IP only from these ranges and
# refuses every other peer, so a stale file locks out new Cloudflare ranges.
#
# Usage: update-cloudflare-ips.sh [--check]
#   --check  Write nothing; exit 1 when the published ranges differ.
# CLOUDFLARE_IPS_BASE_URL replaces https://www.cloudflare.com (tests, mirrors).
# After an update, run `docker compose restart edge`.
set -euo pipefail

cd "$(dirname "$0")"
target=cloudflare-ips.caddy
base="${CLOUDFLARE_IPS_BASE_URL:-https://www.cloudflare.com}"
check=false
case "${1:-}" in
  --check) check=true ;;
  '') ;;
  *) echo 'Usage: update-cloudflare-ips.sh [--check]' >&2; exit 2 ;;
esac

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# Reads one published list, one CIDR per line, and rejects anything else so a
# changed or truncated response never becomes the edge's trust list.
read_list() {
  local name="$1" pattern="$2" count=0 line
  curl --fail --silent --show-error --location --max-time 30 "$base/$name" > "$work/$name"
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    [ -z "$line" ] && continue
    if ! [[ "$line" =~ $pattern ]]; then
      echo "Unexpected entry in $base/$name: $line" >&2
      exit 1
    fi
    printf '%s\n' "$line" >> "$work/ranges"
    count=$((count + 1))
  done < "$work/$name"
  if [ "$count" -eq 0 ]; then
    echo "$base/$name lists no ranges" >&2
    exit 1
  fi
}

: > "$work/ranges"
read_list ips-v4 '^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$'
read_list ips-v6 '^[0-9A-Fa-f:]+/[0-9]{1,3}$'

current_ranges() {
  [ -f "$target" ] || return 0
  sed -n 's/^[[:space:]]*\([0-9A-Fa-f.:]*\/[0-9]*\).*/\1/p' "$target"
}

if [ "$(current_ranges)" = "$(cat "$work/ranges")" ]; then
  echo "$target already matches Cloudflare's published ranges."
  exit 0
fi

if [ "$check" = true ]; then
  echo "$target differs from Cloudflare's published ranges:" >&2
  diff <(current_ranges) "$work/ranges" >&2 || true
  exit 1
fi

{
  echo "# Cloudflare's published proxy ranges for the Cloudflare edge mode."
  echo "# Generated by update-cloudflare-ips.sh from $base/ips-v4"
  echo "# and $base/ips-v6. Do not edit by hand."
  echo "# Retrieved: $(date -u +%Y-%m-%d)"
  echo 'trusted_proxies static \'
  sed -e 's/^/	/' -e '$!s/$/ \\/' "$work/ranges"
} > "$work/$target"
diff <(current_ranges) "$work/ranges" || true
mv "$work/$target" "$target"
echo "Updated $target. Run 'docker compose restart edge' to apply it."
